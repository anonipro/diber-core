#!/usr/bin/env node

const fs = require('fs');
const { parseArgs } = require('util');
const { buildExperimentReport } = require('../engine.js');

const args = process.argv.slice(2);
const command = args[0];


/* ============================================================
   UTILITIES
   ============================================================ */

function exitWithError(message) {
    console.error(`Error: ${message}`);
    process.exit(1);
}

function readJsonFile(filePath) {
    return JSON.parse(
        fs.readFileSync(filePath, 'utf8')
    );
}

function parseRateThreshold(value, flagName) {
    const parsed = Number(value);

    if (!Number.isFinite(parsed)) {
        throw new Error(
            `${flagName} must be a valid number.`
        );
    }

    if (parsed < 0 || parsed > 1) {
        throw new Error(
            `${flagName} must be between 0 and 1.`
        );
    }

    return parsed;
}

function parsePositiveInteger(value, flagName) {
    const parsed = Number(value);

    if (
        !Number.isInteger(parsed) ||
        parsed <= 0
    ) {
        throw new Error(
            `${flagName} must be a positive integer.`
        );
    }

    return parsed;
}

function requireMetric(metrics, metricName) {
    const value = metrics[metricName];

    if (!Number.isFinite(value)) {
        throw new Error(
            `Required metric "${metricName}" is missing or not numeric.`
        );
    }

    return value;
}

function getHallucinationMetric(metrics) {
    /*
     * v0.9.0+
     */
    if (
        Number.isFinite(
            metrics.gt_hallucination_rate
        )
    ) {
        return {
            name: 'gt_hallucination_rate',
            value: metrics.gt_hallucination_rate
        };
    }

    /*
     * Backward compatibility with older reports.
     */
    if (
        Number.isFinite(
            metrics.hallucination_rate
        )
    ) {
        console.warn(
            'Warning: legacy "hallucination_rate" detected. ' +
            'Use reports generated by DIBER Core v0.9.0 or later.'
        );

        return {
            name: 'hallucination_rate',
            value: metrics.hallucination_rate
        };
    }

    throw new Error(
        'Required hallucination metric is missing or not numeric.'
    );
}

function selectRun(report, runId) {
    if (
        !Array.isArray(report.runs) ||
        report.runs.length === 0
    ) {
        throw new Error(
            'The report contains no valid runs to analyze.'
        );
    }

    if (runId) {
        const run = report.runs.find(
            item => item.run_id === runId
        );

        if (!run) {
            throw new Error(
                `Run "${runId}" was not found in the report.`
            );
        }

        return run;
    }

    /*
     * Default behavior:
     * use the final valid run in experiment order.
     */
    return report.runs[
        report.runs.length - 1
    ];
}


/* ============================================================
   COMMAND VALIDATION
   ============================================================ */

if (!command) {
    console.error(
        'Usage: diber <command> [options]'
    );
    console.error('');
    console.error('Commands:');
    console.error('  evaluate   Generate an evaluation report');
    console.error('  assert     Apply CI/CD quality gates');
    process.exit(1);
}


/* ============================================================
   EVALUATE
   ============================================================ */

if (command === 'evaluate') {
    try {
        const options = {
            truth: {
                type: 'string'
            },

            evals: {
                type: 'string'
            },

            out: {
                type: 'string'
            },

            'max-comparisons': {
                type: 'string'
            },

            'max-scanned-pairs': {
                type: 'string'
            },

            'include-multidimensional': {
                type: 'boolean'
            },

            'include-indeterminate': {
                type: 'boolean'
            }
        };

        const { values } = parseArgs({
            args: args.slice(1),
            options,
            strict: true
        });

        if (
            !values.truth ||
            !values.evals
        ) {
            exitWithError(
                'The --truth and --evals parameters are required.'
            );
        }

        const groundTruth =
            readJsonFile(values.truth);

        const testRuns =
            readJsonFile(values.evals);

        if (
            !testRuns.experiment ||
            !testRuns.evaluations
        ) {
            throw new Error(
                'The evaluations file must contain both "experiment" and "evaluations".'
            );
        }

        const comparisonOptions = {};

        if (
            values['max-comparisons'] !==
            undefined
        ) {
            comparisonOptions.maxComparisons =
                parsePositiveInteger(
                    values['max-comparisons'],
                    '--max-comparisons'
                );
        }

        if (
            values['max-scanned-pairs'] !==
            undefined
        ) {
            comparisonOptions.maxScannedPairs =
                parsePositiveInteger(
                    values['max-scanned-pairs'],
                    '--max-scanned-pairs'
                );
        }

        if (
            values['include-multidimensional'] !==
            undefined
        ) {
            comparisonOptions.includeMultidimensional =
                values[
                    'include-multidimensional'
                ];
        }

        if (
            values['include-indeterminate'] !==
            undefined
        ) {
            comparisonOptions.includeIndeterminate =
                values[
                    'include-indeterminate'
                ];
        }

        const report =
            buildExperimentReport({
                experiment:
                    testRuns.experiment,

                groundTruth,

                evaluations:
                    testRuns.evaluations,

                options: {
                    comparisons:
                        comparisonOptions
                }
            });

        if (values.out) {
            fs.writeFileSync(
                values.out,
                JSON.stringify(
                    report,
                    null,
                    2
                )
            );

            console.log(
                `Report successfully generated in: ${values.out}`
            );
        } else {
            console.log(
                JSON.stringify(
                    report,
                    null,
                    2
                )
            );
        }

    } catch (error) {
        console.error(
            'Processing error:',
            error.message
        );
        process.exit(1);
    }


/* ============================================================
   ASSERT
   ============================================================ */

} else if (command === 'assert') {
    try {
        const options = {
            'max-hallucination': {
                type: 'string'
            },

            'max-math-error': {
                type: 'string'
            },

            'min-quality': {
                type: 'string'
            },

            'max-extra-hallucination-penalty': {
                type: 'string'
            },

            'run-id': {
                type: 'string'
            }
        };

        const {
            values,
            positionals
        } = parseArgs({
            args: args.slice(1),
            options,
            allowPositionals: true,
            strict: true
        });

        const reportPath =
            positionals[0];

        if (!reportPath) {
            exitWithError(
                'Please specify the report file path (e.g., ./report.json).'
            );
        }

        const report =
            readJsonFile(reportPath);

        const targetRun =
            selectRun(
                report,
                values['run-id']
            );

        const metrics =
            targetRun.metrics;

        if (!metrics) {
            throw new Error(
                `Run "${targetRun.run_id}" contains no metrics.`
            );
        }

        let failed = false;

        console.log(
            `Auditing run: ${targetRun.run_id}`
        );


        /* ----------------------------------------------------
           Ground Truth hallucination rate
           ---------------------------------------------------- */

        if (
            values['max-hallucination'] !==
            undefined
        ) {
            const threshold =
                parseRateThreshold(
                    values[
                        'max-hallucination'
                    ],
                    '--max-hallucination'
                );

            const hallucinationMetric =
                getHallucinationMetric(
                    metrics
                );

            if (
                hallucinationMetric.value >
                threshold
            ) {
                console.error(
                    `❌ Deployment blocked: ${hallucinationMetric.name} ` +
                    `(${hallucinationMetric.value}) exceeds the maximum ` +
                    `allowed threshold of ${threshold}.`
                );

                failed = true;
            }
        }


        /* ----------------------------------------------------
           Mathematical error rate
           ---------------------------------------------------- */

        if (
            values['max-math-error'] !==
            undefined
        ) {
            const threshold =
                parseRateThreshold(
                    values[
                        'max-math-error'
                    ],
                    '--max-math-error'
                );

            const value =
                requireMetric(
                    metrics,
                    'math_error_rate'
                );

            if (value > threshold) {
                console.error(
                    `❌ Deployment blocked: math_error_rate (${value}) ` +
                    `exceeds the maximum allowed threshold of ${threshold}.`
                );

                failed = true;
            }
        }


        /* ----------------------------------------------------
           Addressed quality
           ---------------------------------------------------- */

        if (
            values['min-quality'] !==
            undefined
        ) {
            const threshold =
                parseRateThreshold(
                    values['min-quality'],
                    '--min-quality'
                );

            /*
             * --min-quality intentionally maps to
             * addressed_quality for backward CLI compatibility.
             */
            const value =
                requireMetric(
                    metrics,
                    'addressed_quality'
                );

            if (value < threshold) {
                console.error(
                    `❌ Deployment blocked: addressed_quality (${value}) ` +
                    `is below the minimum threshold of ${threshold}.`
                );

                failed = true;
            }
        }


        /* ----------------------------------------------------
           Extra hallucination penalty
           ---------------------------------------------------- */

        if (
            values[
                'max-extra-hallucination-penalty'
            ] !== undefined
        ) {
            const threshold = Number(
                values[
                    'max-extra-hallucination-penalty'
                ]
            );

            if (
                !Number.isFinite(threshold) ||
                threshold < 0
            ) {
                throw new Error(
                    '--max-extra-hallucination-penalty must be a non-negative number.'
                );
            }

            const value =
                requireMetric(
                    metrics,
                    'absolute_extra_hallucination_penalty'
                );

            if (value > threshold) {
                console.error(
                    `❌ Deployment blocked: absolute_extra_hallucination_penalty ` +
                    `(${value}) exceeds the maximum allowed threshold of ${threshold}.`
                );

                failed = true;
            }
        }


        /* ----------------------------------------------------
           Final result
           ---------------------------------------------------- */

        if (failed) {
            process.exit(1);
        }

        console.log(
            '✅ Deterministic audit successfully passed. Deployment permitted.'
        );

        process.exit(0);

    } catch (error) {
        console.error(
            'Fatal error during assert execution:',
            error.message
        );

        process.exit(1);
    }


/* ============================================================
   UNKNOWN COMMAND
   ============================================================ */

} else {
    console.error(
        `Unknown command: ${command}. Use 'evaluate' or 'assert'.`
    );

    process.exit(1);
}
